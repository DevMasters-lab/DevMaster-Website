export function getSubcategoriesForCategory(categoryId: string): readonly TechnologySkillSubcategory[] {
  return technologySkillSubcategories.filter(subcategory => subcategory.categoryId === categoryId);
}

export function getSkillsForSubcategory(subcategoryId: string): readonly TechnologySkill[] {
  return technologySkills.filter(skill => skill.subcategoryIds.includes(subcategoryId));
}

export function getSkillsForCategory(categoryId: string): readonly TechnologySkill[] {
  const subcategoryIds = new Set(getSubcategoriesForCategory(categoryId).map(subcategory => subcategory.id));
  return technologySkills.filter(skill => skill.subcategoryIds.some(id => subcategoryIds.has(id)));
}
